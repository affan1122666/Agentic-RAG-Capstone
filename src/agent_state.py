from typing import TypedDict


class AgentState(TypedDict, total=False):
    # ============================================================
    # USER INPUT
    # ============================================================

    question: str

    # ============================================================
    # PLANNING
    # ============================================================

    plan: str

    # ============================================================
    # SOURCE SELECTION
    # ============================================================

    source_selection: str

    # ============================================================
    # LOCAL RETRIEVAL
    # ============================================================

    retrieved_context: str
    sources: list[str]

    # ============================================================
    # WEB RETRIEVAL
    # ============================================================

    web_context: str
    web_sources: list[str]

    # ============================================================
    # ANSWER GENERATION
    # ============================================================

    draft_answer: str

    # ============================================================
    # SELF-CRITIQUE
    # ============================================================

    critique: str

    # ============================================================
    # REVISION
    # ============================================================

    revision_count: int

    # ============================================================
    # FINAL OUTPUT
    # ============================================================

    final_answer: str

    # ============================================================
    # TRACE / LOGGING
    # ============================================================

    trace: list[str]

    # ============================================================
    # PERFORMANCE / TIMING
    # ============================================================

    timings: dict[str, float]